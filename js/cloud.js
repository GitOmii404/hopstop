window.testSupabaseConnection = async function () {
  const url = document.getElementById('supabaseUrlInput')?.value.trim();
  const key = document.getElementById('supabaseKeyInput')?.value.trim();

  if (!url || !key) {
    showToast('Please enter both Project URL and Anon Key ⚠️');
    return;
  }

  const btn = document.getElementById('btnTestCloud');
  if (btn) btn.textContent = '⏳ Testing...';

  try {
    const testClient = supabase.createClient(url, key);
    const { data, error } = await testClient.from('posts').select('id').limit(1);

    if (error && error.code !== 'PGRST116') {
      throw error;
    }

    showToast('✅ Supabase connected successfully! Database tables verified.');
  } catch (err) {
    showToast(`❌ Connection failed: ${err.message || 'Check URL & Key'}`);
  } finally {
    if (btn) btn.textContent = '🔍 Test Connection';
  }
};

