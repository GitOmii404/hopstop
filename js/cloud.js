function initSupabase() {
  const storedUrl = localStorage.getItem(SUPABASE_STORAGE_URL_KEY);
  const storedKey = localStorage.getItem(SUPABASE_STORAGE_KEY_KEY);

  const urlInput = document.getElementById('supabaseUrlInput');
  const keyInput = document.getElementById('supabaseKeyInput');
  if (urlInput && storedUrl) urlInput.value = storedUrl;
  if (keyInput && storedKey) keyInput.value = storedKey;

  const sqlBox = document.getElementById('sqlSchemaPreviewBox');
  if (sqlBox) sqlBox.textContent = HOPSTOP_SQL_SCHEMA;

  if (storedUrl && storedKey && typeof supabase !== 'undefined' && supabase.createClient) {
    try {
      supabaseClient = supabase.createClient(storedUrl, storedKey);
      isCloudConnected = true;
      updateCloudStatusUI(true);
      fetchCloudPosts();
      setupRealtimeSubscriptions();
    } catch (err) {
      console.warn('Supabase initialization failed:', err);
      isCloudConnected = false;
      updateCloudStatusUI(false);
    }
  } else {
    isCloudConnected = false;
    updateCloudStatusUI(false);
  }
}

function updateCloudStatusUI(connected) {
  const badgeBtn = document.getElementById('cloudStatusBtn');
  const label = document.getElementById('cloudStatusLabel');
  const modalPill = document.getElementById('cloudModalStatusPill');
  const modalText = document.getElementById('cloudModalStatusText');

  if (connected) {
    if (badgeBtn) {
      badgeBtn.className = 'cloud-status-badge connected';
      badgeBtn.title = 'Supabase Cloud Connected (Multi-device live sync)';
    }
    if (label) label.textContent = '🟢 Cloud Live';
    if (modalPill) modalPill.className = 'cloud-status-badge connected';
    if (modalText) modalText.textContent = 'Live PostgreSQL Connected';
  } else {
    if (badgeBtn) {
      badgeBtn.className = 'cloud-status-badge disconnected';
      badgeBtn.title = 'Click to connect Supabase free cloud backend';
    }
    if (label) label.textContent = '⚪ Local Storage';
    if (modalPill) modalPill.className = 'cloud-status-badge disconnected';
    if (modalText) modalText.textContent = 'Local Storage (Offline Mode)';
  }
}

async function fetchCloudPosts() {
  if (!supabaseClient) return;

  try {
    const { data: posts, error } = await supabaseClient
      .from('posts')
      .select(`
        *,
        comments (
          id,
          author_name,
          author_avatar,
          text,
          created_at
        )
      `)
      .order('created_at', { ascending: false });

    if (error) {
      console.warn('Error fetching cloud posts:', error.message);
      return;
    }

    if (posts && posts.length > 0) {
      // Map Supabase rows to HopStop post structure
      const mappedPosts = posts.map(row => {
        const comments = (row.comments || []).map(c => ({
          id: c.id,
          author: c.author_name,
          avatar: c.author_avatar,
          text: c.text,
          time: formatRelativeTime(c.created_at)
        }));

        return {
          id: row.id,
          title: row.title,
          placeName: row.place_name,
          country: row.country,
          locationQuery: row.location_query,
          coords: [row.lat, row.lng],
          gemScore: row.gem_score,
          category: row.category,
          categoryLabel: row.category_label,
          readTime: row.read_time || '5 min read',
          date: formatRelativeTime(row.created_at),
          bestTime: row.best_time,
          budget: row.budget,
          author: {
            name: row.author_name,
            handle: row.author_handle,
            avatar: row.author_avatar
          },
          image: row.image_url,
          excerpt: row.excerpt,
          secretTip: row.secret_tip,
          fullContent: row.full_content,
          likes: row.likes_count || 0,
          isLiked: false,
          comments: comments
        };
      });

      postsData = mappedPosts;
      localStorage.setItem('hopstop_community_posts', JSON.stringify(postsData));
      renderAppFeed();
      renderPosts();
      plotMapPins();
    }
  } catch (e) {
    console.error('Failed to sync cloud posts:', e);
  }
}

function setupRealtimeSubscriptions() {
  if (!supabaseClient) return;
  if (realtimeChannel) {
    supabaseClient.removeChannel(realtimeChannel);
  }

  try {
    realtimeChannel = supabaseClient
      .channel('hopstop_live_updates')
      .on('postgres_changes', { event: '*', schema: 'public', table: 'posts' }, (payload) => {
        console.log('Realtime post update received:', payload);
        fetchCloudPosts();
        showToast('⚡ Live update received from another explorer!');
      })
      .on('postgres_changes', { event: '*', schema: 'public', table: 'comments' }, (payload) => {
        console.log('Realtime comment received:', payload);
        fetchCloudPosts();
      })
      .subscribe();
  } catch (err) {
    console.warn('Realtime subscription error:', err);
  }
}

