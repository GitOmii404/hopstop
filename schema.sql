-- 6. Create Travel Bounties Table (Crowdsourced Discovery)
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.bounties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_name TEXT NOT NULL DEFAULT 'Wanderer',
  creator_avatar TEXT NOT NULL DEFAULT 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?auto=format&fit=crop&w=150&q=80',
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'nature',
  target_region TEXT NOT NULL,
  reward_xp INT NOT NULL DEFAULT 500,
  status TEXT NOT NULL DEFAULT 'active', -- 'active' or 'solved'
  solved_by TEXT DEFAULT NULL,
  solved_place TEXT DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Create User Badges Table
CREATE TABLE IF NOT EXISTS public.user_badges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_handle TEXT NOT NULL,
  badge_key TEXT NOT NULL,
  title TEXT NOT NULL,
  icon TEXT NOT NULL,
  description TEXT NOT NULL,
  unlocked_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(user_handle, badge_key)
);

ALTER TABLE public.bounties ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_badges ENABLE ROW LEVEL SECURITY;

