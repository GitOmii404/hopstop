-- 1. Create Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  name TEXT NOT NULL,
  handle TEXT UNIQUE NOT NULL,
  avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?auto=format&fit=crop&w=150&q=80',
  bio TEXT DEFAULT 'Exploring underrated places worldwide ✈️',
  followers_count INT DEFAULT 0,
  following_count INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Posts Table (Hidden Gems & Travel Blogs)
CREATE TABLE IF NOT EXISTS public.posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL DEFAULT 'Explorer',
  author_handle TEXT NOT NULL DEFAULT '@explorer',
  author_avatar TEXT NOT NULL DEFAULT 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?auto=format&fit=crop&w=150&q=80',
  title TEXT NOT NULL,
  place_name TEXT NOT NULL,
  country TEXT NOT NULL,
  location_query TEXT NOT NULL,
  lat FLOAT NOT NULL DEFAULT 40.0,
  lng FLOAT NOT NULL DEFAULT 15.0,
  gem_score TEXT NOT NULL DEFAULT '9.8',
  category TEXT NOT NULL DEFAULT 'village',
  category_label TEXT NOT NULL DEFAULT 'Hidden Village',
  read_time TEXT DEFAULT '5 min read',
  best_time TEXT DEFAULT 'Spring & Autumn',
  budget TEXT DEFAULT '$40 - $70 / day',
  image_url TEXT NOT NULL,
  excerpt TEXT NOT NULL,
  secret_tip TEXT NOT NULL,
  full_content TEXT NOT NULL,
  likes_count INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Comments Table
CREATE TABLE IF NOT EXISTS public.comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT REFERENCES public.posts(id) ON DELETE CASCADE,
  author_name TEXT NOT NULL,
  author_avatar TEXT NOT NULL DEFAULT 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=100&q=80',
  text TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Likes Table
CREATE TABLE IF NOT EXISTS public.likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT REFERENCES public.posts(id) ON DELETE CASCADE,
  user_identifier TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(post_id, user_identifier)
);

-- 5. Create Follows Table
CREATE TABLE IF NOT EXISTS public.follows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  follower_id TEXT NOT NULL,
  following_id TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(follower_id, following_id)
);

-- ============================================================================
-- Enable Row Level Security (RLS) & Public Policies
-- ============================================================================

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.follows ENABLE ROW LEVEL SECURITY;

-- Allow Public Read Access for Feed and Map
CREATE POLICY "Allow public read on profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Allow public read on posts" ON public.posts FOR SELECT USING (true);
CREATE POLICY "Allow public read on comments" ON public.comments FOR SELECT USING (true);
CREATE POLICY "Allow public read on likes" ON public.likes FOR SELECT USING (true);
CREATE POLICY "Allow public read on follows" ON public.follows FOR SELECT USING (true);

-- Allow Anonymous/Authenticated Insert Access
CREATE POLICY "Allow public insert on posts" ON public.posts FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public insert on comments" ON public.comments FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public insert on likes" ON public.likes FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete on likes" ON public.likes FOR DELETE USING (true);
CREATE POLICY "Allow public insert on follows" ON public.follows FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete on follows" ON public.follows FOR DELETE USING (true);

